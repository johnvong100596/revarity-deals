/**
 * Revarity Creative Engine — orchestrator
 * ----------------------------------------
 * Implements the pipeline described in .claude/skills/creative-engine/SKILL.md:
 *   1. Strategy  (architect)   → validate configs, build the run manifest.
 *   2. Generate  (implementer) → copy-gen (template 1) + image-prompt-gen (template 2).
 *   3. QA        (reviewer)     → deterministic copy/prompt gate (template 3, text layer).
 *   4. Output    → write the human review queue + run-<ts>.md summary. STOP (human gate).
 *
 * Guardrails enforced in code (DECISIONS.md):
 *   - D-01: pricing guard. Flagged variants may not hardcode a fee/price; projected
 *           income must carry a range + "estimate"/"typical". [PENDING-D01] token only.
 *   - D-03: image prompts must NOT request fabricated people-as-testimonials.
 *   - D-04: this engine NEVER publishes. It stops at output/. Render + upload are downstream.
 *   - Brand kit is law: palette ink/cream/gold, fonts Fraunces/Manrope/JetBrains Mono,
 *           no emoji, no off-brand color.
 *
 * COPY is generated by a real model call (copy_generation model in model-routing.json,
 * honoring template 1 + the D-01 pricing guard); FALLBACK_COPY is used only if the call
 * fails. IMAGE PROMPTS follow template 2. The IMAGE RENDER (render.mjs) and screenshot QA
 * (qa.mjs) run downstream; each creative carries render_status "PENDING_RENDER" until then.
 */

