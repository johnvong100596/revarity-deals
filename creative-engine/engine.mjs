async function callModelText(resolved, prompt) {
  if (resolved.provider === "anthropic") {
    const res = await fetch("https://api.anthropic.com/v1/messages", {
      method: "POST",
      headers: { "x-api-key": process.env.ANTHROPIC_API_KEY, "anthropic-version": "2023-06-01", "content-type": "application/json" },
      body: JSON.stringify({ model: resolved.model, max_tokens: 1500, messages: [{ role: "user", content: prompt + "\n\nReturn ONLY the JSON array." }, { role: "assistant", content: "[" }] }),
    });
    if (!res.ok) throw new Error(`Anthropic ${resolved.model} ${res.status}: ${(await res.text()).slice(0, 160)}`);
    const data = await res.json();
    return "[" + (data?.content?.map((b) => b.text || "").join("") || "");
  }
  const url = `https://generativelanguage.googleapis.com/v1beta/models/${resolved.model}:generateContent`;
  const res = await fetch(url, {
    method: "POST",
    headers: { "Content-Type": "application/json", "x-goog-api-key": process.env.GEMINI_API_KEY },
    body: JSON.stringify({ contents: [{ parts: [{ text: prompt }] }], generationConfig: { responseMimeType: "application/json", temperature: 0.8 } }),
  });
  if (!res.ok) throw new Error(`Gemini ${resolved.model} ${res.status}: ${(await res.text()).slice(0, 160)}`);
  const data = await res.json();
  return data?.candidates?.[0]?.content?.parts?.map((p) => p.text).join("") || "[]";
}

async function generateCopy(angle, n) {
  if (!process.env.GEMINI_API_KEY && !process.env.ANTHROPIC_API_KEY) return null;
  try {
    const txt = await callModelText(COPY_MODEL, copyGenPrompt(angle, n));
    let arr;
    try { arr = JSON.parse(txt); } catch { const m = txt.match(/\[[\s\S]*\]/); arr = m ? JSON.parse(m[0]) : null; }
    if (!Array.isArray(arr) || arr.length < n) return null;
    return arr.slice(0, n).map((v, i) => {
      const variant = { id: String.fromCharCode(65 + i), headline: String(v.headline || "").trim(), body: String(v.body || "").trim(), cta: String(v.cta || "").trim() };
      if (`${variant.headline} ${variant.body} ${variant.cta}`.includes("[PENDING-D01]")) variant.pricing_flag = "PENDING-D01";
      return variant;
    });
  } catch (e) {
    console.warn(`  copy-gen failed for ${angle.id} (${e.message}) — using fallback copy.`);
    return null;
  }
}

// ── ORCHESTRATE ─────────────────────────────────────────────────────────────────
function ts() {
  const d = new Date();
  const p = (n) => String(n).padStart(2, "0");
  return `${d.getUTCFullYear()}${p(d.getUTCMonth() + 1)}${p(d.getUTCDate())}-${p(d.getUTCHours())}${p(d.getUTCMinutes())}${p(d.getUTCSeconds())}`;
}

async function run() {
  const problems = validateConfigs();
  console.log("=== Creative Engine run ===");
  console.log("mode:", RUN.mode, "| angles:", RUN.angle_ids.join(", "), "| variants:", RUN.variants_per_angle, "| formats:", RUN.formats.join(", "));
  if (problems.length) {
    console.error("CONFIG VALIDATION FAILED:");
    problems.forEach((p) => console.error("  - " + p));
    process.exit(1);
  }
  console.log("config validation: OK (brand, ad-angles, model-routing all load + valid)");
  console.log(`copy-gen model: ${COPY_MODEL.model}${COPY_MODEL.fellBack ? ` (fallback for ${COPY_MODEL.fellBack})` : ""}\n`);

  const stamp = ts();
  const rows = [];
  let pass = 0, fail = 0;
  const skipped = [];

  for (const angleId of RUN.angle_ids) {
    const angle = angles.angles.find((a) => a.id === angleId);
    const generated = await generateCopy(angle, RUN.variants_per_angle);
    const variants = generated || (FALLBACK_COPY[angleId] || []).slice(0, RUN.variants_per_angle);
    console.log(generated ? `  ${angleId}: generated ${variants.length} variants via ${COPY_MODEL.model}` : `  ${angleId}: using fallback copy`);
    if (!variants.length) { console.error(`  ${angleId}: NO COPY (model failed, no fallback) — angle dropped`); skipped.push(angleId); continue; }
    const angleDir = path.join(OUT, angleId);
    fs.mkdirSync(angleDir, { recursive: true });

    for (const variant of variants) {
      for (const fmt of RUN.formats) {
        const spec = { name: fmt, ...brand.creative_specs[fmt] };
        const imagePrompt = buildImagePrompt(angle, variant, spec);
        const qa = qaCreative(angle, variant, spec, imagePrompt);

        const base = `${variant.id}-${fmt}`;
        const record = {
          angle_id: angleId,
          variant: variant.id,
          spec: fmt,
          dimensions: `${spec.w}x${spec.h}`,
          headline: variant.headline,
          body: variant.body,
          cta: variant.cta,
          pricing_flag: variant.pricing_flag || null,
          render_status: "PENDING_RENDER",
          render_route: {
            task: "image_render",
            engine: routing.tasks.image_render.engine,
            draft_model: routing.tasks.image_render.model,
            final_model: routing.tasks.image_render.final_render_model,
            prompt_file: `${base}.prompt.txt`,
          },
          qa,
        };

        const dest = qa.text_layer_verdict === "pass" ? angleDir : path.join(OUT, "_parked");
        fs.mkdirSync(dest, { recursive: true });
        fs.writeFileSync(path.join(dest, `${base}.json`), JSON.stringify(record, null, 2));
        fs.writeFileSync(path.join(dest, `${base}.prompt.txt`), imagePrompt + "\n");

        if (qa.text_layer_verdict === "pass") pass++; else fail++;
        rows.push({ angleId, v: variant.id, fmt, dims: record.dimensions, headline: variant.headline, verdict: qa.text_layer_verdict, reasons: qa.reasons });
      }
    }
  }

  // run summary (the human-gate table)
  const lines = [];
  lines.push(`# Creative Engine run — ${stamp}`);
  lines.push("");
  lines.push(`- **Mode:** ${RUN.mode}`);
  lines.push(`- **Angles:** ${RUN.angle_ids.join(", ")}`);
  lines.push(`- **Variants/angle:** ${RUN.variants_per_angle} · **Formats:** ${RUN.formats.join(", ")}`);
  lines.push(`- **Creatives generated:** ${pass + fail}  (text-QA pass: ${pass}, parked: ${fail})`);
  lines.push(`- **Copy-gen model:** ${COPY_MODEL.model}${COPY_MODEL.fellBack ? ` (fallback for ${COPY_MODEL.fellBack})` : ""}`);
  lines.push(`- **Render status:** \`PENDING_RENDER\` — \`render.mjs\` (Nano Banana / Gemini) renders next, then \`qa.mjs\` screens. Run the whole thing via \`pipeline.mjs\`.`);
  lines.push("");
  lines.push("> **HUMAN GATE.** Nothing here is published. After image render + screenshot QA, David/Malcolm approve before any upload. The engine does not cross this line. (D-04)");
  lines.push("");
  lines.push("| Angle | Var | Format | Dims | Text-QA | Headline | QA notes |");
  lines.push("|---|---|---|---|---|---|---|");
  for (const r of rows) {
    lines.push(`| ${r.angleId} | ${r.v} | ${r.fmt} | ${r.dims} | ${r.verdict} | ${r.headline.replace(/\|/g, "\\|")} | ${(r.reasons.join("; ") || "—").replace(/\|/g, "\\|")} |`);
  }
  lines.push("");
  lines.push("## Pipeline (run via creative-engine/pipeline.mjs)");
  lines.push("1. `render.mjs` — render each prompt with Nano Banana (draft gemini-3.1-flash-image-preview; pro only on text-fidelity need).");
  lines.push("2. `qa.mjs` — automated screenshot QA (reviewer per model-routing; escalates on uncertain).");
  lines.push("3. `regen.mjs` — re-roll any parked failures with the QA hint (up to 2x).");
  lines.push("4. `contactsheet.mjs` → review.html, then the HUMAN approval gate. Engine never publishes. (D-04)");
  lines.push("");

  const summaryPath = path.join(OUT, `run-${stamp}.md`);
  fs.writeFileSync(summaryPath, lines.join("\n"));

  console.log(`generated ${pass + fail} creatives → ${pass} queued, ${fail} parked`);
  console.log(`run summary: creative-engine/output/run-${stamp}.md`);
  console.log("STOP: human gate. Engine does not publish. (D-04)");
  if (skipped.length) {
    console.error(`\nERROR: ${skipped.length} angle(s) produced no copy and were dropped: ${skipped.join(", ")}. ` +
      `Set ANTHROPIC_API_KEY/GEMINI_API_KEY or add FALLBACK_COPY for them. Failing so an unattended run can't silently lose angles.`);
    process.exitCode = 1;
  }
}

