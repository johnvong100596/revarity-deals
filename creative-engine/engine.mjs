// ── QA PASS (reviewer — prompts.md template 3, text/prompt layer) ───────────────
const BANNED_HYPE = ["revolutionary", "insane", "game-changing", "game changing", "unbelievable", "secret"];
const EMOJI = /[\u{1F300}-\u{1FAFF}\u{2600}-\u{27BF}\u{2190}-\u{21FF}\u{2B00}-\u{2BFF}]/u; // arrows like → excluded below
const ARROW_OK = /[→←]/g; // → is allowed as a CTA glyph, not an emoji

function qaCreative(angle, variant, spec, imagePrompt) {
  const reasons = [];
  const copyText = `${variant.headline} ${variant.body} ${variant.cta}`;
  const lc = copyText.toLowerCase();

  // 1. hype words
  for (const w of BANNED_HYPE) if (lc.includes(w)) reasons.push(`banned hype word: "${w}"`);

  // 2. emoji (arrows allowed)
  if (EMOJI.test(copyText.replace(ARROW_OK, ""))) reasons.push("emoji present in copy");

  // 3. pricing guard (D-01) — applies to EVERY variant, flagged or not
  const feeWordNearMoney = /(?:fee|setup|deposit|price|cost|pricing|retainer)\b[^.]{0,16}\$\s?\d|\$\s?\d[\d,]*\s?[kK]?[^.]{0,12}(?:fee|setup|deposit|retainer)/i;
  if (feeWordNearMoney.test(copyText) && !copyText.includes("[PENDING-D01]"))
    reasons.push("states a fee/price near a $ figure without the [PENDING-D01] token (D-01 violation)");
  if (/\$\s?375\b|\$\s?(?:12|35)\s?[kK]\b|\$\s?(?:12|35)[,.]?\d{3}\b/i.test(copyText))
    reasons.push("hardcoded the locked $375 / $12K / $35K pricing figures (D-01 violation)");

  // 4. projected income must be a range AND labeled estimate/typical (brand voice)
  const moneyMonth = copyText.match(/\$\s?\d[\d,]*(?:\s*[–-]\s*\$?\d[\d,]*)?\s*\/?\s*(?:mo\b|month)/i);
  if (moneyMonth) {
    const hasRange = /[–-]/.test(moneyMonth[0]);
    const hasEstimateWord = /\b(estimate|typical|range)\b/i.test(copyText);
    if (!(hasRange && hasEstimateWord)) reasons.push("projected income must be a RANGE and labeled 'estimate'/'typical' (brand voice / D-01)");
  }

  // 5. image-prompt brand checks
  const ipl = imagePrompt.toLowerCase();
  if (/(purple|saas-blue|neon)/.test(ipl) && !/no purple|no saas-blue|no neon/.test(ipl)) reasons.push("image prompt requests off-brand color");
  if (!/(testimonial|talking-head|fabricated)/.test(ipl)) reasons.push("image prompt missing explicit no-fabricated-person guard (D-03)");
  if (!/(ink|cream|gold)/.test(ipl)) reasons.push("image prompt does not reference the brand palette");

  // 6. spec dimensions present
  if (!spec.w || !spec.h) reasons.push("spec missing dimensions");

  // image-level checks (garbled text, rendered color, headline legibility) require the
  // rendered PNG → cannot run until image_render produces an asset.
  const textVerdict = reasons.length === 0 ? "pass" : "fail";
  return {
    text_layer_verdict: textVerdict,
    reasons,
    image_layer_verdict: "PENDING_RENDER",
    image_layer_note: "image-layer QA (garbled text / color / headline legibility) runs in qa.mjs after render.",
    qa_model: routing.tasks.qa_review.model,
  };
}

